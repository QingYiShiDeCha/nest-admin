/**
 * 登录类接口的限流阈值。
 *
 * 刻意写成常量而不是环境变量：@Throttle 是装饰器，在类定义时求值，
 * 那时 ConfigModule 还没加载 .env，读到的会是空值。
 * 全局限流仍由环境变量控制，只有这里的严格阈值是固定的。
 *
 * 按 IP 统计。不按用户名统计是为了避免攻击者用错误密码反复请求，
 * 把某个真实账号锁死——那是把防护变成了拒绝服务的入口。
 */
export const LOGIN_THROTTLE = {
  /** 窗口时长，毫秒 */
  ttl: 60_000,
  /** 窗口内允许的尝试次数 */
  limit: 5,
} as const;
